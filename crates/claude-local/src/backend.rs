/// CoworkVMService (LocalSystem) doesn't inherit Claude's `--proxy-server`. Before launch
/// write temp config with only `egressProxyUrl` to Claude-3p/configLibrary, so Claude
/// passes local proxy to VM. Doesn't overwrite existing user configLibrary, let normal 1p switch flow handle.
fn apply_egress_proxy_config(sets: &[ProfileSet], port: u16) -> Result<()> {
    let meta = serde_json::to_vec_pretty(&json!({
        "appliedId": EGRESS_CONFIG_ID,
        "entries": [{ "id": EGRESS_CONFIG_ID, "name": "ClaudeLocal" }],
        EGRESS_MANAGED_MARKER: true,
    }))?;
    let entry = serde_json::to_vec_pretty(&json!({
        "egressProxyUrl": format!("http://127.0.0.1:{port}"),
    }))?;
    for (idx, set) in sets.iter().enumerate() {
        // Main collection must write; other collections write when parent dir exists (overwrites classic + MSIX virtualized paths).
        if idx > 0 && !set.three_p.exists() && !set.three_p.parent().is_some_and(Path::exists) {
            continue;
        }
        let library = set.three_p.join("configLibrary");
        if library.exists() && !is_managed_egress_config_library(&library) {
            crate::host::diagnostic(
                "claude_local.egress_config_library_present",
                json!({ "path": library }),
            );
            continue;
        }
        let created = !library.exists();
        let result = (|| -> Result<()> {
            fs::create_dir_all(&library)
                .with_context(|| format!("Failed to create {}", library.display()))?;
            // Write config first, then marked meta: meta is the "write complete" flag.
            crate::fsutil::atomic_write(&library.join(format!("{EGRESS_CONFIG_ID}.json")), &entry)?;
            crate::fsutil::atomic_write(&library.join("_meta.json"), &meta)?;
            Ok(())
        })();
        if result.is_err() && created {
            let _ = fs::remove_dir_all(&library);
        }
        result?;
    }
    Ok(())
}

fn remove_managed_egress_config_libraries(sets: &[ProfileSet]) -> Result<()> {
    for set in sets {
        let library = set.three_p.join("configLibrary");
        if is_managed_egress_config_library(&library) {
            fs::remove_dir_all(&library)
                .with_context(|| format!("Failed to clean temp {}", library.display()))?;
            let _ = fs::remove_dir(&set.three_p);
        }
    }
    Ok(())
}

/// Handle `configLibrary` backup left from last switch when state file is already gone.
///
/// Normal flow restores backup via `restore_real_profile` per state file. State file lost (crash,
/// deleted mid-way) gets stuck here: backup persists, `apply_real_profile_one_p` rejects every launch.
/// So handle per situation: target missing -> put backup back; target exists (Claude rebuilt it)
/// -> keep target, archive backup to state's `backups/`, nobody loses.
fn recover_orphan_config_library(sets: &[ProfileSet], root: &Path) -> Result<Option<String>> {
    // State file still recognizes this backup: belongs to normal switch flow, hand to restore_real_profile.
    // Recognize both old and new formats: new lists individually in configLibraryBackups, old format is single
    // configLibraryMoved + configLibraryBackup。
    let tracked = |backup: &Path| {
        let backup = backup.to_string_lossy().into_owned();
        let Some(state) = fs::read(switch_state_path(root))
            .ok()
            .and_then(|bytes| serde_json::from_slice::<Value>(&bytes).ok())
        else {
            return false;
        };
        if let Some(list) = state["configLibraryBackups"].as_array() {
            return list
                .iter()
                .any(|entry| entry["backup"].as_str() == Some(backup.as_str()));
        }
        state["configLibraryMoved"].as_bool() == Some(true)
            && state["configLibraryBackup"].as_str() == Some(backup.as_str())
    };
    let mut notes = Vec::new();
    for set in sets {
        let target = set.three_p.join("configLibrary");
        let backup = target.with_file_name(CONFIG_LIBRARY_BACKUP);
        if !backup.exists() || tracked(&backup) {
            continue;
        }
        if is_managed_egress_config_library(&target) || is_managed_gateway_library(&target) {
            fs::remove_dir_all(&target)
                .with_context(|| format!("Failed to clean temp {}", target.display()))?;
        }
        if !target.exists() {
            fs::rename(&backup, &target)
                .with_context(|| format!("Failed to restore {}", target.display()))?;
            notes.push(format!(
                "Restored last leftover configLibrary backup: {}",
                target.display()
            ));
            continue;
        }
        let archive = root.join("backups");
        private_dir(&archive)?;
        let stamp = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|elapsed| elapsed.as_millis())
            .unwrap_or_default();
        let mut archived = archive.join(format!("configLibrary-orphan-{stamp}"));
        for index in 1.. {
            if !archived.exists() {
                break;
            }
            archived = archive.join(format!("configLibrary-orphan-{stamp}-{index}"));
        }
        fs::rename(&backup, &archived)
            .with_context(|| format!("Failed to archive leftover {}", backup.display()))?;
        notes.push(format!(
            "Archived last leftover configLibrary backup to {}",
            archived.display()
        ));
    }
    Ok((!notes.is_empty()).then(|| notes.join("\n")))
}

fn apply_real_profile_one_p(sets: &[ProfileSet], root: &Path) -> Result<()> {
    apply_real_profile(sets, root, "1p")
}

/// Switch real Claude profile to `mode` (full-featured mode uses `1p`, third-party uses `3p`):
/// change deploymentMode, move existing configLibrary aside, record as-is in state file, `restore_real_profile` restores per it.
/// Already switched to same mode does nothing; switching to other mode restores first then switches.
fn apply_real_profile(sets: &[ProfileSet], root: &Path, mode: &str) -> Result<()> {
    recover_orphan_config_library(sets, root)?;
    let state_path = switch_state_path(root);
    if state_path.exists() {
        let state: Value = serde_json::from_slice(&fs::read(&state_path)?)?;
        ensure!(
            state["applied"].as_bool() == Some(true),
            "Claude local mode switch state file inconsistent, check {SWITCH_STATE_FILE}"
        );
        // Old state file has no mode field, all full-featured mode (1p).
        if state["mode"].as_str().unwrap_or("1p") == mode {
            return Ok(());
        }
        restore_real_profile(sets, root)?;
    }
    private_dir(root)?;
    let mut original = serde_json::Map::new();
    for config_path in desktop_config_paths(sets) {
        let key = config_path.to_string_lossy().into_owned();
        if fs::symlink_metadata(&config_path).is_ok_and(|m| m.file_type().is_symlink()) {
            bail!("Claude config cannot be symlink: {}", config_path.display());
        }
        match fs::read(&config_path) {
            Ok(bytes) => {
                let mut config: Value = serde_json::from_slice(&bytes)
                    .with_context(|| format!("{} is not valid JSON", config_path.display()))?;
                let obj = config
                    .as_object_mut()
                    .context("Claude config must be JSON object")?;
                original.insert(
                    key,
                    obj.get("deploymentMode").cloned().unwrap_or(Value::Null),
                );
                if obj.get("deploymentMode").and_then(Value::as_str) != Some(mode) {
                    obj.insert("deploymentMode".into(), json!(mode));
                    crate::fsutil::atomic_write(
                        &config_path,
                        &serde_json::to_vec_pretty(&config)?,
                    )?;
                }
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                original.insert(key, Value::Null);
            }
            Err(error) => return Err(error.into()),
        }
    }
    // Each profile group's configLibrary must be moved aside (Windows may have classic + MSIX multiple groups).
    let mut libraries = Vec::new();
    for set in sets {
        let library = set.three_p.join("configLibrary");
        let backup = library.with_file_name(CONFIG_LIBRARY_BACKUP);
        if backup.exists() {
            bail!(
                "Claude-3p has unrecovered configLibrary backup, handle {} first",
                backup.display()
            );
        }
        if library.exists() {
            libraries.push((library, backup));
        }
    }
    let mut moved = Vec::new();
    for (library, backup) in libraries {
        fs::rename(&library, &backup)
            .with_context(|| format!("Failed to move aside {}", library.display()))?;
        moved.push(json!({
            "target": library.to_string_lossy(),
            "backup": backup.to_string_lossy(),
        }));
    }
    let state = json!({
        "applied": true,
        "mode": mode,
        "deploymentMode": Value::Object(original),
        "configLibraryBackups": Value::Array(moved),
    });
    crate::fsutil::atomic_write(&state_path, &serde_json::to_vec_pretty(&state)?)?;
    Ok(())
}

fn restore_real_profile(sets: &[ProfileSet], root: &Path) -> Result<()> {
    remove_managed_egress_config_libraries(sets)?;
    // This program's third-party config must be deleted first, then original configLibrary can go back.
    remove_gateway_libraries(sets)?;
    // State file lost still need to finish leftover backup first, otherwise switching back to 3p it'll block next launch.
    recover_orphan_config_library(sets, root)?;
    let state_path = switch_state_path(root);
    if !state_path.exists() {
        return Ok(());
    }
    let state: Value = serde_json::from_slice(&fs::read(&state_path)?)?;
    if let Some(map) = state["deploymentMode"].as_object() {
        for (path, original) in map {
            let config_path = PathBuf::from(path);
            if !config_path.exists() {
                continue;
            }
            let mut config: Value = serde_json::from_slice(&fs::read(&config_path)?)?;
            let obj = match config.as_object_mut() {
                Some(obj) => obj,
                None => continue,
            };
            match original {
                Value::Null => {
                    obj.remove("deploymentMode");
                }
                value => {
                    obj.insert("deploymentMode".into(), value.clone());
                }
            }
            crate::fsutil::atomic_write(&config_path, &serde_json::to_vec_pretty(&config)?)?;
        }
    }
    if let Some(list) = state["configLibraryBackups"].as_array() {
        for entry in list {
            let backup = PathBuf::from(entry["backup"].as_str().unwrap_or_default());
            let target = PathBuf::from(entry["target"].as_str().unwrap_or_default());
            if backup.exists() && !target.exists() {
                fs::rename(&backup, &target)
                    .with_context(|| format!("Failed to restore {}", target.display()))?;
            }
        }
    } else if state["configLibraryMoved"].as_bool() == Some(true) {
        // Old format (only recorded primary group's backup) must also be readable.
        let backup = PathBuf::from(state["configLibraryBackup"].as_str().unwrap_or(""));
        if let Some(target) = sets.first().map(|set| set.three_p.join("configLibrary"))
            && backup.exists()
            && !target.exists()
        {
            fs::rename(&backup, &target)
                .with_context(|| format!("Failed to restore {}", target.display()))?;
        }
    }
    fs::remove_file(&state_path).ok();
    Ok(())
}

