// Full-featured mode follows PoC approach: reuse real Claude profile, need to change
// claude_desktop_config.json's deploymentMode to 1p and move
// Claude-3p/configLibrary aside. Changes recorded to <state>/real-profile-switch.json,
// on stop/switch back to 3p restore per record, ensuring idempotent rollback.
const SWITCH_STATE_FILE: &str = "real-profile-switch.json";
const CONFIG_LIBRARY_BACKUP: &str = "configLibrary.codex-plus-backup";
/// Third-party mode config written by this program into `Claude-3p/configLibrary`: fixed id, `_meta.json` marked,
/// restore only deletes marked ones (user's own or other tools' configLibrary always moved aside first, put back after).
const GATEWAY_CONFIG_ID: &str = "00000000-0000-4000-8000-636c6175646d";
const GATEWAY_CONFIG_MARKER: &str = "claudeDeskDownGateway";

/// Claude third-party mode inference config: inference via local service (validates with upstream Key, carries both auth headers,
/// translates model names, strips diagnostics before forwarding to upstream), model list from upstream with display names.
fn gateway_config_entry(port: u16, upstream: &Upstream) -> Value {
    let mut names: Vec<&str> = Vec::new();
    for model in std::iter::once(&upstream.default_model).chain(upstream.models.iter()) {
        let model = model.trim();
        if !model.is_empty() && !names.contains(&model) {
            names.push(model);
        }
    }
    let models: Vec<Value> = names
        .into_iter()
        .map(|model| {
            match upstream
                .model_names
                .get(model)
                .and_then(|value| value["name"].as_str())
                .map(str::trim)
                .filter(|label| !label.is_empty() && *label != model)
            {
                Some(label) => json!({ "name": model, "labelOverride": label }),
                None => json!(model),
            }
        })
        .collect();
    json!({
        "inferenceProvider": "gateway",
        "inferenceGatewayBaseUrl": format!("http://127.0.0.1:{port}"),
        "inferenceGatewayApiKey": upstream.token,
        "inferenceGatewayAuthScheme": "bearer",
        "inferenceModels": models,
        "modelDiscoveryEnabled": false,
        "disableDeploymentModeChooser": true,
    })
}

fn is_managed_gateway_library(library: &Path) -> bool {
    fs::read(library.join("_meta.json"))
        .ok()
        .and_then(|bytes| serde_json::from_slice::<Value>(&bytes).ok())
        .is_some_and(|meta| meta[GATEWAY_CONFIG_MARKER].as_bool() == Some(true))
}

/// Write this program's third-party mode config. Caller must have `apply_real_profile(.., "3p")` already moved existing configLibrary.
/// Write config first, then write marked `_meta.json`: mid-failure means no meta in dir, Claude won't use it;
/// newly created dir on failure deleted directly, no orphan dirs of unknown origin.
fn write_gateway_library(sets: &[ProfileSet], entry: &Value) -> Result<()> {
    let meta = serde_json::to_vec_pretty(&json!({
        "appliedId": GATEWAY_CONFIG_ID,
        "entries": [{ "id": GATEWAY_CONFIG_ID, "name": "ClaudeDeskDown" }],
        GATEWAY_CONFIG_MARKER: true,
    }))?;
    let entry = serde_json::to_vec_pretty(entry)?;
    for (index, set) in sets.iter().enumerate() {
        // Main collection must write; other collections (Windows MSIX virtualized dirs) only write if Claude already created them.
        if index > 0 && !set.three_p.is_dir() {
            continue;
        }
        let library = set.three_p.join("configLibrary");
        if library.exists() && !is_managed_gateway_library(&library) {
            bail!("{} still has other configs, couldn't move aside, please exit Claude and try again", library.display());
        }
        let created = !library.exists();
        let write = || -> Result<()> {
            private_dir(&library)?;
            write_private(&library.join(format!("{GATEWAY_CONFIG_ID}.json")), &entry)?;
            write_private(&library.join("_meta.json"), &meta)?;
            Ok(())
        };
        if let Err(error) = write() {
            if created {
                let _ = fs::remove_dir_all(&library);
            }
            return Err(error.context(format!("Failed to write {}", library.display())));
        }
    }
    Ok(())
}

fn remove_gateway_libraries(sets: &[ProfileSet]) -> Result<()> {
    for set in sets {
        let library = set.three_p.join("configLibrary");
        if is_managed_gateway_library(&library) {
            fs::remove_dir_all(&library)
                .with_context(|| format!("Failed to clean {}", library.display()))?;
        }
    }
    Ok(())
}

/// 1p + Cowork temp VM egress config: fixed id, separate marker, only delete own writes.
const EGRESS_CONFIG_ID: &str = "00000000-0000-4000-8000-636c61756465";
const EGRESS_MANAGED_MARKER: &str = "claudeLocalManaged";

/// A set of Claude Desktop profile directories: data holds 1p userData (claude_desktop_config.json, Cache, claude-code-sessions),
/// mode is the Claude dir where deploymentMode is written, three_p is 3p mode userData. On macOS data and mode are the same.
struct ProfileSet {
    data: PathBuf,
    mode: PathBuf,
    three_p: PathBuf,
}

fn profile_sets() -> Vec<ProfileSet> {
    #[cfg(target_os = "windows")]
    {
        let roaming = std::env::var_os("APPDATA").map(PathBuf::from);
        let local = std::env::var_os("LOCALAPPDATA").map(PathBuf::from);
        return profile_sets_for(true, &home_dir(), roaming.as_deref(), local.as_deref());
    }
    #[cfg(not(target_os = "windows"))]
    profile_sets_for(false, &home_dir(), None, None)
}

/// Pure computation part: directories injected by caller, testable on mac for Windows layout.
///
/// First group on Windows is classic install (data in `%APPDATA%`, mode/3p in `%LOCALAPPDATA%`);
/// then each `Claude_*` / `AnthropicPBC.Claude_*` package under `%LOCALAPPDATA%\Packages`
/// (case-insensitive, sorted) gets one MSIX virtualized directory group. APPDATA/LOCALAPPDATA missing falls back to
/// `home\AppData\Roaming|Local`. First returned group is primary.
fn profile_sets_for(
    windows: bool,
    home: &Path,
    roaming: Option<&Path>,
    local: Option<&Path>,
) -> Vec<ProfileSet> {
    if !windows {
        let support = home.join("Library/Application Support");
        return vec![ProfileSet {
            data: support.join("Claude"),
            mode: support.join("Claude"),
            three_p: support.join("Claude-3p"),
        }];
    }
    let roaming = roaming
        .map(Path::to_path_buf)
        .unwrap_or_else(|| home.join("AppData").join("Roaming"));
    let local = local
        .map(Path::to_path_buf)
        .unwrap_or_else(|| home.join("AppData").join("Local"));
    let mut sets = vec![ProfileSet {
        data: roaming.join("Claude"),
        mode: local.join("Claude"),
        three_p: local.join("Claude-3p"),
    }];
    let mut packages: Vec<PathBuf> = fs::read_dir(local.join("Packages"))
        .into_iter()
        .flatten()
        .filter_map(|entry| entry.ok())
        .filter(|entry| {
            let name = entry.file_name().to_string_lossy().to_string();
            ["Claude_", "AnthropicPBC.Claude_"].iter().any(|prefix| {
                name.get(..prefix.len())
                    .is_some_and(|value| value.eq_ignore_ascii_case(prefix))
            }) && entry.path().is_dir()
        })
        .map(|entry| entry.path())
        .collect();
    // read_dir order unstable, sort for reproducible results.
    packages.sort();
    for package in packages {
        let cache = package.join("LocalCache");
        sets.push(ProfileSet {
            data: cache.join("Roaming").join("Claude"),
            mode: cache.join("Local").join("Claude"),
            three_p: cache.join("Local").join("Claude-3p"),
        });
    }
    sets
}

/// Each group's deploymentMode configs: taken in data, mode, three_p order, deduplicated.
fn desktop_config_paths(sets: &[ProfileSet]) -> Vec<PathBuf> {
    let mut paths: Vec<PathBuf> = Vec::new();
    for set in sets {
        for dir in [&set.data, &set.mode, &set.three_p] {
            let path = dir.join("claude_desktop_config.json");
            if !paths.contains(&path) {
                paths.push(path);
            }
        }
    }
    paths
}

