/// Set config directory for built-in Claude Code.
///
/// - Share `~/.claude`: **don't set** `CLAUDE_CONFIG_DIR` (setting it makes Claude Code read `~/.claude/.claude.json`,
///   different from command line's `~/.claude.json`), also remove inherited same-named var; previous session records in isolated dirs merged into
///   `~/.claude/projects` (only missing, no overwrite).
/// - Isolated dir: `~/.claude-desktop-local/claude-code`, and merge earlier records from each state dir.
fn apply_code_dir(command: &mut Command, root: &Path, share_home: bool, home_claude: &Path) -> Result<()> {
    if share_home {
        command.env_remove("CLAUDE_CONFIG_DIR");
        for legacy in [full_code_dir(root), root.join("claude-code")] {
            merge_projects(&legacy, home_claude);
        }
    } else {
        let code_dir = full_code_dir(root);
        private_dir(&code_dir)?;
        merge_legacy_full_code_dir(&root.join("claude-code"), &code_dir);
        command.env("CLAUDE_CONFIG_DIR", &code_dir);
    }
    Ok(())
}

/// Merge session records from one config directory's `projects/` into another (only missing files, existing dir perms untouched).
fn merge_projects(from_config: &Path, to_config: &Path) {
    let from = from_config.join("projects");
    if from_config == to_config || !from.is_dir() {
        return;
    }
    if let Err(error) = copy_missing_keep_existing(&from, &to_config.join("projects")) {
        let _ = crate::host::diagnostic(
            "claude_local.merge_projects_failed",
            serde_json::json!({ "message": format!("{error:#}") }),
        );
    }
}

fn copy_missing_keep_existing(from: &Path, to: &Path) -> Result<()> {
    if !to.exists() {
        fs::create_dir_all(to)?;
    }
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let kind = entry.file_type()?;
        let target = to.join(entry.file_name());
        if kind.is_dir() {
            copy_missing_keep_existing(&entry.path(), &target)?;
        } else if kind.is_file() && !target.exists() {
            fs::copy(entry.path(), &target)?;
        }
    }
    Ok(())
}

/// Before sharing directory, session records in each state dir's `claude-code/`: before launch copy missing files to shared directory.
/// Only copy files not yet in shared directory, no overwrite, no delete original; copy failure only logs, doesn't block launch.
fn merge_legacy_full_code_dir(legacy: &Path, shared: &Path) {
    if legacy == shared || !legacy.is_dir() {
        return;
    }
    if let Err(error) = copy_missing(legacy, shared) {
        let _ = crate::host::diagnostic(
            "claude_local.merge_code_dir_failed",
            serde_json::json!({ "message": format!("{error:#}") }),
        );
    }
}

fn copy_missing(from: &Path, to: &Path) -> Result<()> {
    private_dir(to)?;
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let kind = entry.file_type()?;
        let target = to.join(entry.file_name());
        if kind.is_dir() {
            copy_missing(&entry.path(), &target)?;
        } else if kind.is_file() && !target.exists() {
            fs::copy(entry.path(), &target)?;
        }
    }
    Ok(())
}

fn private_file(path: &Path) -> Result<File> {
    let mut options = OpenOptions::new();
    options.create(true).truncate(true).write(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let file = options.open(path)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        file.set_permissions(fs::Permissions::from_mode(0o600))?;
    }
    Ok(file)
}

fn write_private(path: &Path, bytes: &[u8]) -> Result<()> {
    private_file(path)?.write_all(bytes)?;
    Ok(())
}

